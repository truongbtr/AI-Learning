/** Hai ô sai quanh đáp án, mỗi ô mang đúng mã của con số đó. */
function N(ans, kinds, g = {}) {
  const out = [];
  for (const k of kinds) {
    const v = {
      dem_thieu_1: ans - 1,
      dem_thua_1: ans + 1,
      nham_cong_tru: g.opp,
      lap_lai_tong: g.rep,
    }[k];
    if (v == null || v < 0 || v === ans || out.some(([t]) => t === String(v))) continue;
    out.push([String(v), k]);
    if (out.length === 2) break;
  }
  if (!out.length) out.push([String(ans + 1), "dem_thua_1"]);
  return out;
}
const Q = (q, ans, kinds, g, d, hint, why) => ({
  q,
  right: String(ans),
  wrongs: N(ans, kinds, g),
  d,
  hint,
  why,
});
const L = (say, ans, kinds, g, d, q) => ({
  say,
  right: String(ans),
  wrongs: N(ans, kinds, g),
  d,
  ...(q ? { q } : {}),
});
const box = (q, ans, d, hint) => ({
  q,
  items: [
    [String(ans)],
    [String(ans - 1), null, "dem_thieu_1"],
    [String(ans + 1), null, "dem_thua_1"],
  ],
  zones: [["Answer"]],
  key: { 0: [0] },
  d,
  hint,
  why: `The answer is ${ans}.`,
});

