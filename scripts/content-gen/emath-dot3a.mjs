// ─────────────────────────────────────────────────────────── count on / count back ───────────
function countPack({ code, prefix, std, dir: way, facts, listens, counts, reads, writes, note }) {
  const on = way === "on";
  sentencePack({
    ...base,
    code,
    prefix,
    src: CCSS(std, on ? "counting on to add" : "counting back to subtract"),
    note,
    items: facts.map(([a, b], i) => {
      const ans = on ? a + b : a - b;
      const q = [
        `Start at ${a}, count ${way} ${b}. Where do you stop?`,
        `${a} ${on ? "+" : "-"} ${b} = ?  Count ${way} from ${a}.`,
        `Count ${way} ${b} from ${a}. What number?`,
      ][i % 3];
      // Đếm cả số bắt đầu: count on dừng sớm một (ans−1), count back dừng muộn một (ans+1).
      const kinds = on ? ["dem_thieu_1", "dem_thua_1"] : ["dem_thua_1", "dem_thieu_1"];
      return Q(
        q,
        ans,
        kinds,
        {},
        1 + (i % 5),
        `Say ${a} in your head, then count ${b} ${on ? "up" : "down"} on your fingers.`,
        `${a}… ${Array.from({ length: b }, (_, k) => (on ? a + k + 1 : a - k - 1)).join(", ")}. The answer is ${ans}.`,
      );
    }),
    listenPrompts: [
      "Listen, then tap where you stop.",
      "{ban} says where to start. Tap the answer!",
      "Listen carefully, then count.",
      "Where do you stop? Tap it.",
      "Listen again and pick one.",
      "Count in your head, then tap.",
    ],
    listens: listens.map(([a, b], i) =>
      L(
        `Start at ${EN[a]}. Count ${way} ${EN[b]}.`,
        on ? a + b : a - b,
        on ? ["dem_thieu_1", "dem_thua_1"] : ["dem_thua_1", "dem_thieu_1"],
        {},
        1 + (i % 5),
      ),
    ),
    places: facts
      .slice(0, 5)
      .map(([a, b], i) =>
        box(
          `Count ${way} ${b} from ${a}. Drag the stop.`,
          on ? a + b : a - b,
          2 + (i % 4),
          `Start at ${a}, then ${b} jumps.`,
        ),
      ),
    counts,
    reads,
    writes,
  });
}
